def _executemany(
    connection: psycopg.Connection[Any],
    query: str,
    parameters: Any,
) -> None:
    with connection.cursor() as cursor:
        cursor.executemany(query, parameters)


async def initialize_database(database_url: str) -> Database:
    pool = ConnectionPool(
        conninfo=database_url,
        min_size=1,
        max_size=4,
        timeout=15,
        kwargs={
            "row_factory": dict_row,
            "connect_timeout": 10,
            "options": "-c statement_timeout=10000",
        },
        open=False,
    )
    database = Database(pool)
    try:
        await database.open()
        await database.run(_initialize_schema)
    except Exception:
        await database.close()
        raise
    return database


def _start_embedded_postgres(
    data_directory: Path,
) -> pgembed.PostgresServer:
    data_directory.parent.mkdir(parents=True, exist_ok=True)
    try:
        original_pg_ctl = pgembed_commands.pg_ctl
    except AttributeError as error:
        raise RuntimeError(
            "pgembed is missing pg_ctl.exe; reinstall pgembed in this Python environment"
        ) from error

    def pg_ctl_with_separate_log(
        arguments: list[str],
        **kwargs: Any,
    ) -> str:
        command_arguments = list(arguments)
        if "-l" in command_arguments:
            log_argument = command_arguments.index("-l") + 1
            if log_argument >= len(command_arguments):
                raise ValueError("pg_ctl -l requires a log file path")
            command_arguments[log_argument] = str(
                data_directory.parent / f"{data_directory.name}-pgembed-server.log"
            )
        command_kwargs = dict(kwargs)
        command_kwargs["timeout"] = PGEMBED_START_TIMEOUT_SECONDS
        return original_pg_ctl(command_arguments, **command_kwargs)

    # Keep pg_ctl's output separate from PostgreSQL's recovery log path.
    with PGEMBED_START_LOCK:
        pgembed_commands.pg_ctl = pg_ctl_with_separate_log
        try:
            server = pgembed.get_server(data_directory, cleanup_mode="stop")
        finally:
            pgembed_commands.pg_ctl = original_pg_ctl
    return server.__enter__()


async def initialize_embedded_database(
    data_directory: Path,
) -> tuple[Database, pgembed.PostgresServer]:
    server = await asyncio.to_thread(_start_embedded_postgres, data_directory)
    try:
        database = await initialize_database(server.get_uri())
    except BaseException:
        await asyncio.to_thread(server.__exit__, None, None, None)
        raise
    return database, server


async def close_embedded_postgres(server: pgembed.PostgresServer) -> None:
    # Exiting stop mode preserves the data directory; cleanup() deletes it.
    await asyncio.to_thread(server.__exit__, None, None, None)


